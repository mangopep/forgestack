package costguard

import (
	"encoding/json"
	"fmt"
	"regexp"
	"slices"
)

// knownCostlyResourceTypes classifies Terraform resource *types* that
// reliably carry meaningful ongoing cost regardless of usage -- a NAT
// gateway or a load balancer bills hourly from the moment it exists, not
// just when traffic flows. This is a short, hand-curated classification
// list, not a pricing catalog: it names no dollar amount, only "this
// category of resource needs explicit sign-off before it's created."
var knownCostlyResourceTypes = map[string]string{
	"aws_nat_gateway":         "NAT gateways bill hourly plus per-GB data processing from creation, regardless of idle traffic.",
	"aws_eks_cluster":         "EKS has a flat hourly control-plane charge in addition to any node compute.",
	"aws_eks_node_group":      "A managed node group provisions EC2 instances that bill independently of the EKS control plane.",
	"aws_lb":                  "Application/Network Load Balancers bill hourly plus LCU usage charges.",
	"aws_elb":                 "Classic Load Balancers bill hourly plus data-processing charges.",
	"aws_db_instance":         "RDS instances bill hourly plus storage/backup/IOPS, and keep billing until deleted (not just while idle).",
	"aws_rds_cluster":         "Aurora clusters bill per instance plus storage/IO.",
	"aws_elasticache_cluster": "ElastiCache nodes bill hourly regardless of utilization.",
	"aws_redshift_cluster":    "Redshift nodes bill hourly regardless of query volume.",
	"aws_ebs_volume":          "EBS volumes bill for provisioned size/IOPS from creation, independent of attachment or use.",
	"aws_efs_file_system":     "EFS bills for stored data and, if provisioned-throughput mode is used, for that throughput too.",
}

// largeInstanceTypePattern flags instance-type strings this repo treats as
// large enough to require explicit approval: anything 4xlarge or bigger,
// "metal" (bare-metal, billed as the largest size in its family), or a
// GPU/accelerator family prefix. This is a pattern over instance *names*,
// not a price list -- it says nothing about what any of them cost.
var largeInstanceTypePattern = regexp.MustCompile(
	`^(?:[a-z0-9]+\.(?:4|8|9|10|12|16|18|24|32|48|metal)x?large$|(?:p|g|inf|trn|dl|f)\d[a-z]?\.[a-z0-9]+$)`,
)

// IsLargeInstanceType reports whether instanceType matches the large/
// accelerated pattern above.
func IsLargeInstanceType(instanceType string) bool {
	return instanceType != "" && largeInstanceTypePattern.MatchString(instanceType)
}

// terraformPlan is the minimal subset of Terraform's own `terraform show
// -json <plan>` schema this package reads. It is Terraform's documented
// plan format, not anything vendor-specific -- unrelated to any pricing
// tool's own data shape.
type terraformPlan struct {
	ResourceChanges []struct {
		Address      string `json:"address"`
		Type         string `json:"type"`
		ProviderName string `json:"provider_name"`
		Change       struct {
			Actions []string        `json:"actions"`
			After   json.RawMessage `json:"after"`
		} `json:"change"`
	} `json:"resource_changes"`
}

// PlannedResource is one resource this plan will create or update,
// extracted from the plan JSON for cost-risk scanning.
type PlannedResource struct {
	Address      string
	ResourceType string
	InstanceType string // only populated for aws_instance-shaped resources that set "instance_type"
}

// ScanPlan parses Terraform plan JSON (the output of `terraform show -json
// <planfile>`, never generated by this package itself -- see
// docs/architecture/COST-GUARD.md for why) and returns every resource that
// will exist after apply (create or update; a pure delete adds no future
// cost). Malformed JSON is a hard error, not an empty result -- a caller
// must never treat "couldn't parse the plan" as "no costly resources
// found."
func ScanPlan(planJSON []byte) ([]PlannedResource, error) {
	var plan terraformPlan
	if err := json.Unmarshal(planJSON, &plan); err != nil {
		return nil, fmt.Errorf("parse Terraform plan JSON: %w", err)
	}
	var out []PlannedResource
	for _, rc := range plan.ResourceChanges {
		if isDeleteOnly(rc.Change.Actions) {
			continue
		}
		pr := PlannedResource{Address: rc.Address, ResourceType: rc.Type}
		if rc.Type == "aws_instance" && len(rc.Change.After) > 0 {
			var after struct {
				InstanceType string `json:"instance_type"`
			}
			// A decode failure here just means this field isn't present or
			// shaped as expected (e.g. unknown-at-plan-time) -- that's not
			// a reason to fail the whole scan, only to skip the instance-
			// type-specific check for this one resource.
			_ = json.Unmarshal(rc.Change.After, &after)
			pr.InstanceType = after.InstanceType
		}
		out = append(out, pr)
	}
	return out, nil
}

func isDeleteOnly(actions []string) bool {
	if len(actions) == 0 {
		return false
	}
	for _, a := range actions {
		if a != "delete" && a != "no-op" && a != "read" {
			return false
		}
	}
	return true
}

// FlagCostlyResources checks each planned resource against the known-
// costly-type classification and the large-instance-type pattern, and
// marks whether budget explicitly approved that resource type.
func FlagCostlyResources(resources []PlannedResource, budget Budget) []CostlyResourceFlag {
	var flags []CostlyResourceFlag
	for _, r := range resources {
		reason, costly := knownCostlyResourceTypes[r.ResourceType]
		if !costly && r.ResourceType == "aws_instance" && IsLargeInstanceType(r.InstanceType) {
			costly = true
			reason = fmt.Sprintf("instance type %q is a large/accelerated size with substantial hourly cost.", r.InstanceType)
		}
		if !costly {
			continue
		}
		flags = append(flags, CostlyResourceFlag{
			Address:            r.Address,
			ResourceType:       r.ResourceType,
			Reason:             reason,
			ExplicitlyApproved: slices.Contains(budget.ApprovedCostlyResourceTypes, r.ResourceType),
		})
	}
	return flags
}

// FlagCostlyEstimateResources applies the same known-costly-type
// classification directly to a cost estimate's own resource list (not a
// separately-supplied Terraform plan). Evaluate calls this unconditionally
// on every run -- unlike a plan file, an estimate's Resources list is not
// an optional argument a caller could omit to skip the check, so this is
// the trusted, non-bypassable path for the resource-type check. It cannot
// check instance *size* (ResourceCost carries no instance_type field), only
// resource *type* -- FlagCostlyResources against an actual plan remains the
// way to additionally catch large/accelerated instance types.
func FlagCostlyEstimateResources(resources []ResourceCost, budget Budget) []CostlyResourceFlag {
	var flags []CostlyResourceFlag
	for _, r := range resources {
		reason, costly := knownCostlyResourceTypes[r.ResourceType]
		if !costly {
			continue
		}
		flags = append(flags, CostlyResourceFlag{
			Address:            r.Address,
			ResourceType:       r.ResourceType,
			Reason:             reason,
			ExplicitlyApproved: slices.Contains(budget.ApprovedCostlyResourceTypes, r.ResourceType),
		})
	}
	return flags
}
